#!/usr/bin/env node
// DSHmini design-token codegen.
// Single source of truth: frontend/packages/design/tokens.json
// Outputs:
//   frontend/packages/design/generated/tokens.css     (CSS custom properties)
//   apps/macos/Sources/DSHminiApp/Tokens.swift        (AppKit constants)
// Any hand-written color/number outside these outputs is a spec violation.

import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const tokensPath = resolve(root, "frontend/packages/design/tokens.json");
const tokens = JSON.parse(readFileSync(tokensPath, "utf8"));

const isColorPair = (v) =>
  v && typeof v === "object" && "light" in v && "dark" in v;

const cssId = (path) => "--dsh-" + path.join("-");

// ---------- tokens.css ----------
const cssLight = [];
const cssDark = [];
const cssStatic = [];

function walk(obj, prefix = []) {
  for (const [key, value] of Object.entries(obj)) {
    const path = [...prefix, key];
    if (isColorPair(value)) {
      cssLight.push(`  ${cssId(path)}: ${value.light};`);
      cssDark.push(`  ${cssId(path)}: ${value.dark};`);
    } else if (value && typeof value === "object" && !("px" in value) && !("ms" in value)) {
      if (value.light || value.dark) {
        // shadow/motion pareses
        if (isColorPair(value)) continue;
      }
      walk(value, path);
    } else if (value && typeof value === "object") {
      // scalar leaf (number / px / ms / string) — emit raw
      const raw =
        value && typeof value === "object"
          ? value.px ?? value.ms ?? value.width ?? value.linecap ?? value.linejoin ?? value.family ?? value.easing ?? value.scaleFrom ?? value.translateY ?? value.duration
          : value;
      cssStatic.push(`  ${cssId(path)}: ${raw};`);
    } else {
      cssStatic.push(`  ${cssId(path)}: ${value};`);
    }
  }
}
walk(tokens.color);
walk({ radius: tokens.radius });
walk({ space: tokens.space });
walk({ size: tokens.size });

let css = `/* Generated by gen-tokens.mjs — DO NOT EDIT. Source: tokens.json v${tokens.version} */\n:root {\n${cssLight.join("\n")}\n${cssStatic.join("\n")}\n}\n@media (prefers-color-scheme: dark) {\n:root {\n${cssDark.join("\n")}\n}\n}\n`;

const cssOut = resolve(root, "frontend/packages/design/generated/tokens.css");
mkdirSync(dirname(cssOut), { recursive: true });
writeFileSync(cssOut, css);

// ---------- Tokens.swift ----------
const hex = (h) => {
  const m = /^#([0-9a-f]{6})$/i.exec(h);
  if (!m) {
    const r = /^rgba?\(([^)]+)\)/.exec(h);
    if (r) {
      const [a, b, c, d] = r[1].split(",").map((s) => parseFloat(s.trim()));
      return `NSColor(srgbRed: ${(a / 255).toFixed(3)}, green: ${(b / 255).toFixed(3)}, blue: ${(c / 255).toFixed(3)}, alpha: ${(d ?? 1).toFixed(3)})`;
    }
    return "NSColor.black";
  }
  const n = parseInt(m[1], 16);
  return `NSColor(red: ${((n >> 16) & 255) / 255}, green: ${((n >> 8) & 255) / 255}, blue: ${(n & 255) / 255}, alpha: 1)`;
};

const swift = [];
swift.push(`// Generated by gen-tokens.mjs — DO NOT EDIT. Source: tokens.json v${tokens.version}`);
swift.push(`import AppKit`);
swift.push(`
enum Tokens {
    /// Dynamic color: follows appearance (light/dark).
    static func rgba(_ light: String, _ dark: String) -> NSColor {
        NSColor(name: nil) { appearance in
            let darkMode = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua
            return ${"darkMode ? rgba(dark) : rgba(light)"}
        }
    }
    static func rgba(_ s: String) -> NSColor {
        let v = s.trimmingCharacters(in: .whitespaces)
        if v.hasPrefix("#") {
            let m = v.replacingOccurrences(of: "#", with: "")
            let n = UInt32(m, radix: 16) ?? 0
            return NSColor(red: CGFloat((n >> 16) & 255) / 255,
                           green: CGFloat((n >> 8) & 255) / 255,
                           blue: CGFloat(n & 255) / 255, alpha: 1)
        }
        if v.hasPrefix("rgba(") {
            let parts = v.dropFirst(5).dropLast().split(separator: ",").map { $0.trimmingCharacters(in: .whitespaces) }
            let num: (Int) -> CGFloat = { i in CGFloat(Double(parts[i]) ?? 0) }
            return NSColor(srgbRed: num(0)/255, green: num(1)/255, blue: num(2)/255, alpha: parts.count > 3 ? (Double(parts[3]) ?? 1) : 1)
        }
        return NSColor.black
    }
`);

const swiftColors = [];
const swiftScalars = [];

for (const [group, values] of Object.entries(tokens.color)) {
  for (const [name, v] of Object.entries(values)) {
    if (isColorPair(v)) {
      swiftColors.push(`    static let ${group}${cap(name)} = rgba("${v.light}", "${v.dark}")`);
    } else {
      swiftColors.push(`    static let ${group}${cap(name)} = rgba("${v}")`);
    }
  }
}
swift.push(`    enum Color {`);
swift.push(swiftColors.join("\n"));
swift.push(`    }\n`);

for (const [group, values] of Object.entries({ radius: tokens.radius, size: tokens.size })) {
  for (const [name, v] of Object.entries(values)) {
    const f = typeof v === "number" ? v : (v.px ?? v.width ?? 0);
    swiftScalars.push(`    static let ${group}${cap(name)}: CGFloat = ${f}`);
  }
}
swift.push(`    enum Metric {`);
swift.push(swiftScalars.join("\n"));
swift.push(`    }`);
swift.push(`\n}`);

const swiftOut = resolve(root, "apps/macos/Sources/DSHminiApp/Tokens.swift");
writeFileSync(swiftOut, swift.join("\n") + "\n");

console.log(`gen-tokens: wrote tokens.css (${css.length}B) and Tokens.swift (${swift.length} lines)`);

function cap(s) {
  return s.replace(/^[a-z]/, (c) => c.toUpperCase());
}
